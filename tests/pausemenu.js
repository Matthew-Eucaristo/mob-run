const { chromium } = require('playwright');
const assert = (c, m) => { if (!c) { console.log('FAIL:', m); process.exitCode = 1; } else console.log('ok:', m); };
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
  const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto('http://localhost:8787/index.html?debug');
  await p.waitForTimeout(600);
  await p.click('#playBtn');
  await p.waitForTimeout(1500);
  await p.click('#pauseBtn');
  await p.waitForTimeout(200);
  await p.click('#pauseSet');
  await p.waitForTimeout(200);
  assert(await p.isVisible('#settingsOverlay') && await p.evaluate(() => window.__mob.G.mode) === 'paused', 'settings opens from pause, still paused');
  await p.click('#setClose');
  await p.waitForTimeout(150);
  assert(await p.isVisible('#pauseOverlay'), 'back on the pause menu');
  await p.screenshot({ path: 'pause.png' });
  const c0 = await p.evaluate(() => window.__mob.G.coins);
  await p.click('#pauseQuit');
  await p.waitForTimeout(600);
  const st = await p.evaluate(() => ({ m: window.__mob.G.mode, cause: document.getElementById('overCause').textContent, revive: getComputedStyle(document.getElementById('reviveBtn')).display, coins: window.__mob.G.coins }));
  assert(st.m === 'over' && /CALLED/.test(st.cause), 'END RUN goes to results: ' + st.cause);
  assert(st.revive === 'none', 'no revive offered after quitting');
  await p.click('#againBtn');
  await p.waitForTimeout(300);
  assert(await p.evaluate(() => window.__mob.G.mode) === 'run', 'run again works');
  console.log(errs.length ? errs.join('\n') : 'no page errors');
  await b.close();
})();

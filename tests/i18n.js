const { chromium } = require('playwright');
const assert = (c, m) => { if (!c) { console.log('FAIL:', m); process.exitCode = 1; } else console.log('ok:', m); };
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'id-ID', hasTouch: true, isMobile: true });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.addInitScript(() => { if (!sessionStorage.getItem('x')) { localStorage.setItem('mobrun_save', JSON.stringify({ bank: 700, best: 480, hist: [300, 480, 200] })); sessionStorage.setItem('x', '1'); } });
  await p.goto('http://localhost:8787/index.html?debug');
  await p.waitForTimeout(800);
  assert(await p.textContent('#playBtn') === 'MAIN', 'Indonesian device gets MAIN on the play button');
  await p.screenshot({ path: 'id_menu.png' });
  await p.tap('#shopBtn'); await p.waitForTimeout(300);
  await p.screenshot({ path: 'id_shop.png' });
  await p.tap('#shopClose');
  await p.tap('#playBtn'); await p.waitForTimeout(1200);
  await p.evaluate(() => { const M = window.__mob; M.G.cause = 'OUTNUMBERED BY A MOB'; M.G.soldiers = 0; M.beginDeath(); });
  await p.waitForFunction(() => document.getElementById('overOverlay').style.display === 'flex');
  await p.waitForTimeout(1300);
  assert(/GEROMBOLAN/.test(await p.textContent('#overCause')), 'death cause translated');
  await p.screenshot({ path: 'id_over.png' });
  await p.tap('#againBtn'); await p.waitForTimeout(300);
  await p.evaluate(() => { window.__mob.G.dist += 0; });
  await p.reload(); await p.waitForTimeout(800);
  await p.tap('#muteBtn'); await p.waitForTimeout(200);
  await p.screenshot({ path: 'id_set.png' });
  await p.tap('.setRow[data-k="lang"]');
  await p.waitForTimeout(1500);
  assert(await p.textContent('#playBtn') === 'PLAY', 'language toggle switches to English and sticks');
  console.log(errs.length ? errs.join('\n') : 'no page errors');
  await b.close();
})();

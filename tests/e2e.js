const { chromium } = require('playwright');
const assert = (c, m) => { if (!c) { console.log('FAIL:', m); process.exitCode = 1; } else console.log('ok:', m); };
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push('PAGEERR ' + e.message));
  p.on('console', m => { if (m.type() === 'error') errs.push('console ' + m.text()); });
  await p.goto('http://localhost:8787/index.html?debug');
  await p.waitForTimeout(1000);
  const G = () => p.evaluate(() => { const g = window.__mob.G; return { mode: g.mode, coins: g.coins, soldiers: g.soldiers, dist: g.dist, form: g.form, armyX: g.armyX }; });
  const coins0 = (await G()).coins;
  assert(await p.isVisible('#dailyBtn'), 'daily gift visible on fresh save');
  await p.tap('#dailyBtn');
  await p.waitForTimeout(300);
  const coins1 = (await G()).coins;
  assert(coins1 === coins0 + 60, 'daily gift paid 60 (' + coins0 + '->' + coins1 + ')');
  assert(!(await p.isVisible('#dailyBtn')), 'daily gift hidden after claim');
  assert((await G()).mode === 'menu', 'claiming gift did not start the run');

  await p.tap('#shopBtn');
  await p.waitForTimeout(200);
  assert(await p.isVisible('#shopOverlay'), 'armory opens');
  await p.evaluate(() => { window.__mob.G.coins = 500; });
  await p.tap('#shopClose'); await p.tap('#shopBtn');
  const cards = await p.$$('.upCard');
  assert(cards.length === 7, '7 upgrade cards');
  await cards[0].tap();
  await p.waitForTimeout(150);
  const after = await p.evaluate(() => ({ c: window.__mob.G.coins, s: JSON.parse(localStorage.getItem('mobrun_save')) }));
  assert(after.c === 440 && after.s.up.army === 1, 'bought BIGGER SQUAD lvl1 for 60 (coins ' + after.c + ')');
  await p.tap('#shopClose');
  assert((await G()).mode === 'menu', 'closing armory keeps menu');

  await p.tap('#playBtn');
  await p.waitForTimeout(300);
  const st = await G();
  assert(st.mode === 'run' && st.soldiers === 15, 'tap starts run with upgraded 15 soldiers (' + st.soldiers + ')');

  const cdp = await ctx.newCDPSession(p);
  const touch = async (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] });
  const x0 = (await G()).armyX;
  await touch('touchStart', 150, 600);
  for (let i = 1; i <= 8; i++) { await touch('touchMove', 150 + i * 15, 602); await p.waitForTimeout(30); }
  await touch('touchEnd');
  await p.waitForTimeout(500);
  const x1 = (await G()).armyX;
  assert(x1 > x0 + 20, 'swipe right steers right (' + x0.toFixed(0) + '->' + x1.toFixed(0) + ')');
  await touch('touchStart', 200, 600);
  for (let i = 1; i <= 8; i++) { await touch('touchMove', 201, 600 - i * 15); await p.waitForTimeout(30); }
  await touch('touchEnd');
  await p.waitForTimeout(800);
  const f = (await G()).form;
  assert(f < -0.3, 'swipe up packs a column (form ' + f.toFixed(2) + ')');

  await p.waitForTimeout(2500);
  await p.tap('#pauseBtn');
  await p.waitForTimeout(200);
  const d1 = (await G()).dist;
  await p.waitForTimeout(800);
  const pz = await G();
  assert(pz.mode === 'paused' && pz.dist === d1, 'pause button freezes the run');
  await p.screenshot({ path: 'v_pause.png' });
  await p.tap('#pauseOverlay');
  await p.waitForTimeout(500);
  assert((await G()).mode === 'run' && (await G()).dist > d1, 'tap resumes');
  await p.waitForTimeout(2000);
  await p.evaluate(() => { const g = window.__mob.G; g.cause = 'TEST'; g.coins = 400; g.soldiers = 0; g.mode = 'dying'; });
  await p.waitForFunction(() => document.getElementById('overOverlay').style.display === 'flex');
  assert(true, 'game over shows');
  await p.tap('#overStats');
  await p.waitForTimeout(80);
  const mm = await p.evaluate(() => [window.__mob.G.mode, document.getElementById('overOverlay').style.display]); assert(mm[0] === 'over', 'an instant tap on results does not skip them (lockout) ' + mm);
  assert(await p.isVisible('#quickBuy'), 'quick-buy offered with 400 coins');
  const qb0 = await p.evaluate(() => ({ c: window.__mob.G.coins, up: JSON.stringify(window.__mob.META.up) }));
  await p.tap('#quickBuy');
  await p.waitForTimeout(150);
  const qb1 = await p.evaluate(() => ({ c: window.__mob.G.coins, up: JSON.stringify(window.__mob.META.up), mode: window.__mob.G.mode }));
  assert(qb1.c < qb0.c && qb1.up !== qb0.up && qb1.mode === 'over', 'quick-buy buys without leaving results (' + qb0.c + '->' + qb1.c + ')');
  await p.evaluate(() => { window.__mob.G.coins = 400; });
  const o1 = await p.evaluate(() => ({ c: window.__mob.G.coins, d: window.__mob.G.dist }));
  await p.tap('#reviveBtn');
  await p.waitForTimeout(300);
  const r = await G();
  assert(r.mode === 'run' && r.soldiers >= 24, 'revive resumes with soldiers ' + r.soldiers);
  assert(r.coins < o1.c, 'revive costs coins (' + o1.c + '->' + r.coins + ')');
  await p.waitForTimeout(1500);
  await p.evaluate(() => { const g = window.__mob.G; g.soldiers = 0; g.mode = 'dying'; });
  await p.waitForTimeout(1500);
  const o2 = await G();
  const gain = o2.coins - r.coins;
  assert(gain < 60, 'second death pays only the new stretch, not the whole run again (+' + gain + ')');
  assert(!(await p.isVisible('#reviveBtn')), 'revive hidden after use');
  await p.tap('#againBtn');
  await p.waitForTimeout(300);
  assert((await G()).mode === 'run', 'RUN AGAIN restarts');

  await p.reload(); await p.waitForTimeout(900);
  const re = await p.evaluate(() => ({ up: JSON.parse(localStorage.getItem('mobrun_save')).up.army, dailyHidden: !document.getElementById('dailyBtn').classList.contains('on'), menu: document.getElementById('menuMissions').children.length }));
  assert(re.up >= 1, 'upgrades persist after reload (army lvl ' + re.up + ')');
  assert(re.dailyHidden, 'daily gift stays claimed after reload');
  assert(re.menu >= 3, 'menu lists missions after reload');
  console.log(errs.length ? errs.join('\n') : 'no page errors');
  await b.close();
})();

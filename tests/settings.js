const { chromium } = require('playwright');
const assert = (c, m) => { if (!c) { console.log('FAIL:', m); process.exitCode = 1; } else console.log('ok:', m); };
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.addInitScript(() => { if (!sessionStorage.getItem('x')) { localStorage.setItem('mobrun_save', JSON.stringify({ bank: 500, best: 600, hist: [220, 340, 290, 600, 410, 380] })); sessionStorage.setItem('x', '1'); } });
  await p.goto('http://localhost:8787/index.html?debug');
  await p.waitForTimeout(700);
  await p.click('#muteBtn');
  await p.waitForTimeout(200);
  assert(await p.isVisible('#settingsOverlay'), 'gear opens settings');
  await p.screenshot({ path: 'set1.png' });
  const rows = await p.$$('.setRow');
  assert(rows.length === 5 && (await p.$$('.tog')).length === 4, '4 toggles + language row');
  await rows[1].click();
  await p.waitForTimeout(100);
  const st = await p.evaluate(() => JSON.parse(localStorage.getItem('mobrun_settings')));
  assert(st.music === false && st.sfx === true && st.vib === true && st.shake === true, 'music off only: ' + JSON.stringify(st));
  await p.click('#setClose');
  assert(!(await p.isVisible('#settingsOverlay')), 'DONE closes');
  assert(await p.evaluate(() => window.__mob.G.mode) === 'menu', 'still on menu');
  await p.reload(); await p.waitForTimeout(700);
  await p.click('#muteBtn'); await p.waitForTimeout(150);
  const tog = await p.$$eval('.tog', els => els.map(e => e.classList.contains('on')));
  assert(JSON.stringify(tog) === '[true,false,true,true]', 'settings persist ' + JSON.stringify(tog));
  await p.click('#setClose');
  await p.click('#playBtn');
  await p.waitForTimeout(1500);
  await p.evaluate(() => { const M = window.__mob; M.G.cause = 'TEST'; M.G.soldiers = 0; M.beginDeath(); });
  await p.waitForFunction(() => document.getElementById('overOverlay').style.display === 'flex');
  await p.waitForTimeout(1200);
  const bars = await p.$$eval('.hist i', els => els.length);
  assert(bars === 7, 'history shows 7 runs (' + bars + ')');
  await p.screenshot({ path: 'set2.png' });
  console.log(errs.length ? errs.join('\n') : 'no page errors');
  await b.close();
})();
